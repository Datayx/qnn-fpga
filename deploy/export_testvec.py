"""
Export the sweep.py test split for the board, without importing TensorFlow (low RAM).

Writes deploy/testvec/:
  x_float.bin  float32 [N,15]  standardised inputs (CPU baseline)
  x_q.bin      int16   [N,15]  raw ap_fixed<16,6> = floor(x * 2^10), wrapped (FPGA input, AP_TRN/AP_WRAP)
  y.bin        uint8   [N]     labels (g,q,t,w,z = 0..4)
  meta.txt     N, feature order
and deploy/board/cpu_weights.h from the hls4ml weight files (the exact quantised weights in hardware).

The split replicates sweep.load_data() exactly (same OpenML frame, stratified split, seed 42, scaler).
Run:  python deploy/export_testvec.py [--hls hls/mlp_4b]
"""
import argparse
import os

import numpy as np
import pandas as pd
from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

CLASSES = ["g", "q", "t", "w", "z"]
PROTECTED = "mass_mmdt"
HERE = os.path.dirname(os.path.abspath(__file__))


def load_test(seed=42):
    df = fetch_openml("hls4ml_lhc_jets_hlf", as_frame=True).frame
    y = pd.Categorical(df.pop("class"), categories=CLASSES).codes
    X = df.drop(columns=[PROTECTED])
    cols = list(X.columns)
    X = X.to_numpy(np.float32)
    idx = np.arange(len(y))
    tr, te = train_test_split(idx, test_size=0.2, random_state=seed, stratify=y)
    scaler = StandardScaler().fit(X[tr])
    return scaler.transform(X[te]).astype(np.float32), y[te].astype(np.uint8), cols


def to_apfixed_16_6(x):
    raw = np.floor(x.astype(np.float64) * 1024.0).astype(np.int64)   # AP_TRN: toward -inf
    return (((raw + 32768) % 65536) - 32768).astype(np.int16)          # AP_WRAP


def weights_header(hls_dir, path):
    shapes = {"2": (15, 32), "5": (32, 32), "8": (32, 5)}            # fc0, fc1, out (Keras kernel = [in][out])
    lines = ["// Generated by deploy/export_testvec.py from " + hls_dir.replace("\\", "/") + "/firmware/weights",
             "// Exact quantised weights used in hardware; kernel layout [n_in][n_out] row-major.",
             "#pragma once"]
    for k, (n_in, n_out) in shapes.items():
        w = np.loadtxt(os.path.join(hls_dir, "firmware", "weights", f"w{k}.txt"), delimiter=",")
        b = np.loadtxt(os.path.join(hls_dir, "firmware", "weights", f"b{k}.txt"), delimiter=",")
        assert w.size == n_in * n_out and b.size == n_out, (k, w.size, b.size)
        lines.append(f"static const float W{k}[{n_in * n_out}] = {{{', '.join(f'{v:.8e}f' for v in w)}}};")
        lines.append(f"static const float B{k}[{n_out}] = {{{', '.join(f'{v:.8e}f' for v in b)}}};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hls", default=os.path.join(HERE, "..", "hls", "mlp_4b"))
    args = ap.parse_args()
    out = os.path.join(HERE, "testvec")
    os.makedirs(out, exist_ok=True)
    os.makedirs(os.path.join(HERE, "board"), exist_ok=True)

    x, y, cols = load_test()
    xq = to_apfixed_16_6(x)
    x.tofile(os.path.join(out, "x_float.bin"))
    xq.tofile(os.path.join(out, "x_q.bin"))
    y.tofile(os.path.join(out, "y.bin"))
    with open(os.path.join(out, "meta.txt"), "w") as f:
        f.write(f"N {len(y)}\nfeatures {' '.join(cols)}\n")
    weights_header(os.path.normpath(args.hls), os.path.join(HERE, "board", "cpu_weights.h"))
    print(f"N={len(y)}  max|x|={np.abs(x).max():.2f}  class counts={np.bincount(y).tolist()}")
    print(f"wrote {out}/(x_float,x_q,y).bin and board/cpu_weights.h")


if __name__ == "__main__":
    main()
